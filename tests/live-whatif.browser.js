async (page) => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const state = () => page.evaluate(async () => (await fetch("/api/state")).json());
  ensure((await state()).plans.length === 0, "Run only against an isolated server with an empty test database");
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const viewerContext = await page.context().browser().newContext({viewport: {width: 1171, height: 900}});
  const viewer = await viewerContext.newPage();
  viewer.on("pageerror", error => errors.push(error.message));
  const origin = new URL(page.url()).origin;
  const command = async (name, arguments) => page.evaluate(async ({name, arguments}) => {
    const response = await fetch("/mcp", {method: "POST", headers: {"Content-Type": "application/json", "Accept": "application/json, text/event-stream", "MCP-Protocol-Version": "2025-11-25", ...window.PocketAuth.headers()}, body: JSON.stringify({jsonrpc: "2.0", id: 1, method: "tools/call", params: {name, arguments}})});
    const document = await response.json();
    if (!response.ok || document.result?.isError) throw new Error("Synthetic MCP update failed");
    return document.result.structuredContent;
  }, {name, arguments});
  const update = async changes => command("update_plan_item", {plan_id: "example-plan", collection: "activities", item_id: "minimal", changes, expected_revision: (await state()).revision});
  const deadline = async value => command("update_plan", {plan_id: "example-plan", changes: {deadline: value}, expected_revision: (await state()).revision});
  try {
    await page.setViewportSize({width: 1171, height: 900});
    await viewer.goto(origin + "/#plan");
    await viewer.waitForSelector("#live-status[data-state=live]");
    await viewer.evaluate(() => { window.qaMarker = "preserve page"; });
    await page.evaluate(() => window.PocketAuth.login("local-admin"));
    await page.evaluate(async () => {
      const fixture = await (await fetch("/example-plan.json")).json();
      fixture.revision = (await (await fetch("/api/state")).json()).revision;
      const document = fixture.plans[0];
      document.deadline = "2026-10-23";
      document.streams = [{id: "first", name: "First", description: ""}, {id: "second", name: "Second", description: "", dependsOn: "first"}, {id: "other", name: "Other", description: ""}];
      const base = {...document.activities[0], streamId: "first", start: "2026-10-16", durationDays: 1, progress: 0, issueIds: []};
      document.activities = [{...base, id: "minimal", name: "Minimal"}, {...base, id: "heavy", name: "Heavy", dependsOn: "minimal", durationDays: 3}, {...base, id: "later", name: "Later", streamId: "second", durationDays: 2}, {...base, id: "other", name: "Independent", streamId: "other", start: "2026-10-20", durationDays: 2}, {...base, id: "done", name: "Completed", streamId: "other", start: "2026-10-15", progress: 100}];
      document.issues[0].scope = "ACTIVITIES";
      document.issues[0].blocker = true;
      document.issues[0].streamIds = [];
      document.issues[0].activityIds = ["minimal"];
      const response = await fetch("/api/state", {method: "PUT", headers: {"Content-Type": "application/json", ...window.PocketAuth.headers()}, body: JSON.stringify(fixture)});
      if (!response.ok) throw new Error("QA fixture failed");
    });
    await viewer.waitForSelector(".bar[data-id=minimal]");
    await page.waitForSelector(".bar[data-id=minimal]");
    ensure(await viewer.evaluate(() => window.PocketAuth.canEdit === false), "Anonymous viewer must remain read-only");
    await viewer.locator("#range-days").selectOption("28");
    await viewer.locator('[data-toggle-stream="other"]').click();
    await viewer.locator('[data-tab="issues"]').click();
    await viewer.locator("#issue-status-filter").selectOption("history");
    await page.locator('.activity-name[data-id="minimal"]').click();
    await page.locator("#field-progress").fill("25");
    await page.locator('#editor-form button[type=submit]').click();
    await viewer.waitForFunction(() => planner.activities.find(item => item.id === "minimal").progress === 25);
    ensure(await viewer.locator("#issue-status-filter").inputValue() === "history", "Live refresh must preserve filters");
    ensure(await viewer.locator("#panel-issues").isVisible(), "Live refresh must preserve selected tab");
    ensure(await viewer.evaluate(() => window.qaMarker) === "preserve page", "No full page refresh is allowed");
    await viewer.locator('[data-tab="plan"]').click();
    ensure(await viewer.locator("#range-days").inputValue() === "28", "Calendar range must survive updates");
    ensure(await viewer.locator('[data-toggle-stream="other"]').getAttribute("aria-expanded") === "false", "Collapse state must survive updates");

    await page.locator('[data-tab="streams"]').click();
    await page.locator("#add-stream").click();
    await page.locator("#field-name").fill("Added live");
    await page.locator('#editor-form button[type=submit]').click();
    await viewer.waitForSelector('.stream-toggle[aria-label="Collapse Added live"]');
    await page.locator('[data-tab="plan"]').click();
    await page.locator("#add-activity").click();
    await page.locator("#field-name").fill("Added live activity");
    await page.locator("#field-streamId").selectOption({label: "Added live"});
    await page.locator("#field-start").fill("2026-10-20");
    await page.locator('#editor-form button[type=submit]').click();
    await viewer.waitForSelector('.activity-name:text-is("Added live activity")');

    await page.locator('.activity-name[data-id="minimal"]').click();
    const openedRevision = await page.evaluate(() => editorRevision);
    await page.locator("#field-name").fill("Unsaved draft");
    await update({progress: 30});
    await page.waitForSelector("#live-status[data-state=pending]");
    ensure(await page.locator("#field-name").inputValue() === "Unsaved draft", "Remote update must not overwrite draft");
    ensure(await page.evaluate(() => editorRevision) === openedRevision, "Remote update must not rebase draft revision");
    await page.locator('#editor-form button[type=submit]').click();
    await page.waitForFunction(() => !document.getElementById("editor").open);
    ensure((await state()).plans[0].activities[0].name === "Minimal", "Stale draft must not be persisted");
    await viewer.waitForFunction(() => planner.activities.find(item => item.id === "minimal").progress === 30);

    const rootBar = page.locator('.bar[data-id="minimal"]').first();
    const bounds = await rootBar.boundingBox();
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width / 2 + 50, bounds.y + bounds.height / 2);
    await deadline("2026-10-24");
    await page.waitForSelector("#live-status[data-state=pending]");
    await page.mouse.up();
    await page.waitForFunction(() => !mutationPending && !dragPending);
    ensure((await state()).plans[0].activities[0].start === "2026-10-16", "Remote update must keep a stale drag from saving");
    const freshBounds = await rootBar.boundingBox();
    await page.mouse.move(freshBounds.x + freshBounds.width / 2, freshBounds.y + freshBounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(freshBounds.x + freshBounds.width / 2 + 50, freshBounds.y + freshBounds.height / 2);
    await page.mouse.up();
    await viewer.waitForFunction(() => planner.activities.find(item => item.id === "minimal").start === "2026-10-19");
    await update({start: "2026-10-16"});
    await page.waitForFunction(() => planner.activities.find(item => item.id === "minimal").start === "2026-10-16");

    await viewerContext.setOffline(true);
    await viewer.waitForSelector("#live-status[data-state=unavailable]");
    await deadline("2026-10-30");
    await viewerContext.setOffline(false);
    await viewer.waitForFunction(() => planner.deadline === "2026-10-30", null, {timeout: 15000});
    await viewer.waitForSelector("#live-status[data-state=live]");
    ensure(await viewer.evaluate(() => window.qaMarker) === "preserve page", "Reconnect must not reload browser");

    await update({progress: 0});
    await page.waitForFunction(() => planner.activities.find(item => item.id === "minimal").progress === 0);
    await page.locator('[data-tab="plans"]').click();
    await page.locator('.plan-card [data-edit="plan"]').click();
    await page.locator("#field-deadline").fill("2026-10-23");
    await page.locator('#editor-form button[type=submit]').click();
    await page.locator('[data-tab="plan"]').click();
    await viewer.waitForFunction(() => planner.deadline === "2026-10-23");
    await viewer.waitForFunction(() => planner.activities.find(item => item.id === "minimal").progress === 0);

    const baseline = JSON.stringify(await state());
    const viewerWrites = [];
    viewer.on("request", request => { if (request.method() === "PUT") viewerWrites.push(request.url()); });
    await viewer.locator("#whatif-toggle").click();
    await viewer.locator("#whatif-end").fill("2026-10-18");
    ensure(await viewer.locator("#whatif-run").count() === 0, "What if should update without a Preview button");
    await viewer.waitForSelector("#gantt.whatif-active");
    ensure(await viewer.locator('.bar[data-id="minimal"]').getAttribute("data-start") === "2026-10-19", "Blocked work should move in the existing timeline");
    ensure(await viewer.locator('.bar[data-id="minimal"]').count() === 1, "What if must not duplicate tasks");
    ensure((await viewer.locator("#plan-summary").innerText()).includes("3 calendar days past deadline"), "Show deadline overrun separately");
    ensure(JSON.stringify(await state()) === baseline && viewerWrites.length === 0, "Simulation must not write");

    await update({progress: 75});
    await viewer.waitForFunction(() => planner.activities.find(item => item.id === "minimal").progress === 75);
    ensure(await viewer.locator("#whatif-end").inputValue() === "2026-10-18", "Remote updates must preserve the end-date assumption");
    ensure((await viewer.locator("#whatif-error").innerText()) === "", "Percentage preview should need no manual remaining work");
    await viewer.locator("#whatif-plus").click();
    ensure(await viewer.locator("#whatif-end").inputValue() === "2026-10-19", "+1 day does not move the blocker end");
    await viewer.locator("#whatif-minus").click();
    ensure(await viewer.locator("#whatif-end").inputValue() === "2026-10-18", "-1 day does not move the blocker end");
    await viewer.waitForSelector("#gantt.whatif-active");
    const simulated = viewer.locator('.bar[data-id="minimal"]');
    ensure(await simulated.count() === 1 && await simulated.getAttribute("data-start") === "2026-10-16" && await simulated.getAttribute("data-end") === "2026-10-19", "A task should keep one continuous frame through the pause");
    ensure(await simulated.locator(".bar-gap.weekend").count() === 1, "The weekend is not marked inside the frame");
    ensure(await simulated.locator(".bar-label").count() <= 1, "A task name is repeated in projected bar fragments");
    const comparison = viewer.locator(".activity-row").filter({has: viewer.locator('.activity-name[data-id="minimal"]')});
    ensure(await comparison.locator(".bar").count() === 1, "Only one forecast bar should be shown");
    ensure(await comparison.locator(".activity-name").count() === 1, "Activity title is duplicated");
    await viewer.setViewportSize({width: 393, height: 852});
    await viewer.waitForTimeout(100);
    ensure(await viewer.locator("#whatif-toggle").isVisible(), "Preview controls must work on mobile");
    ensure(await viewer.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth && document.documentElement.scrollHeight <= window.innerHeight), "Mobile must not gain page overflow");
    await viewer.screenshot({path: "/tmp/pocketplanner-whatif-mobile.png"});
    await viewer.setViewportSize({width: 1171, height: 900});
    await viewer.screenshot({path: "/tmp/pocketplanner-whatif-desktop.png"});
    await viewer.locator("#whatif-toggle").click();
    ensure(!await viewer.locator("#gantt").evaluate(element => element.classList.contains("whatif-active")), "Close returns to real plan");
    const actual = await state();
    ensure(actual.plans[0].activities[0].start === "2026-10-16" && actual.plans[0].activities[0].durationDays === 1 && actual.plans[0].activities[0].progress === 75, "Simulation leaves activity fields unchanged");
    ensure(viewerWrites.length === 0, "Read-only viewer must never mutate");
    ensure(!errors.length, `Browser errors: ${errors.join("; ")}`);
    return {checks: ["two independent sessions", "UI additions and MCP live updates", "view and draft preservation", "stale save and drag rejected", "live drag propagation", "offline/reconnect", "deadline editor", "single read-only forecast", "percentage-based remaining effort", "calendar +/- one day", "updated assumption on live changes", "mobile layout"], screenshots: ["/tmp/pocketplanner-whatif-desktop.png", "/tmp/pocketplanner-whatif-mobile.png"], revision: actual.revision};
  } finally { await viewerContext.close(); }
}
