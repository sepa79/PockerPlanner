async (page) => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const state = () => page.evaluate(async () => (await fetch("/api/state")).json());
  ensure((await state()).plans.length === 0, "Run only against an empty isolated QA database");
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewportSize({width: 774, height: 772});
  await page.evaluate(async () => {
    await window.PocketAuth.login("local-admin");
    const fixture = await (await fetch("/example-plan.json")).json();
    fixture.revision = (await (await fetch("/api/state")).json()).revision;
    Object.assign(fixture.plans[0].activities[0], {start: "2026-10-13", durationDays: 3, progress: 50});
    Object.assign(fixture.plans[0].issues[0], {blocker: true, discovered: "2026-10-14"});
    const response = await fetch("/api/state", {method: "PUT", headers: {"Content-Type": "application/json", ...window.PocketAuth.headers()}, body: JSON.stringify(fixture)});
    if (!response.ok) throw new Error("Failed to prepare isolated duration fixture");
    await window.PocketAuth.logout();
  });
  await page.reload();
  await page.waitForFunction(() => typeof planner !== "undefined" && planner?.id);
  await page.evaluate(() => { today = () => "2026-10-14"; alertAcknowledged = true; render(); });
  await page.locator(".activity-name").first().click();
  const duration = page.locator("#field-durationDays");
  const minus = page.locator("#duration-minus");
  const plus = page.locator("#duration-plus");
  ensure(await duration.isDisabled() && await minus.isDisabled() && await plus.isDisabled(), "Viewers can change duration");
  ensure((await page.locator("#activity-blocker-delay").innerText()).includes("+1 calendar day"), "Missing estimated finish delay attributable to blockers");
  ensure((await page.locator("#activity-timing").innerText()).includes("Recorded blocking Not recorded"), "Estimated delay must not invent recorded blocking time");
  await page.locator("#close-editor").click();
  await page.evaluate(() => window.PocketAuth.login("local-admin"));
  await page.reload();
  await page.waitForFunction(() => typeof planner !== "undefined" && planner?.id);
  await page.evaluate(() => { today = () => "2026-10-14"; alertAcknowledged = true; render(); });
  await page.locator(".activity-name").first().click();
  const before = await state();
  await plus.click();
  ensure(await duration.inputValue() === "4" && (await page.locator("#activity-timing").innerText()).includes("Estimate 4 working days"), "Plus does not update the full estimate preview");
  await minus.click();
  ensure(await duration.inputValue() === "3", "Minus does not subtract one planned day");
  await duration.press("ArrowUp");
  ensure(await duration.inputValue() === "4", "Native keyboard stepping was lost");
  await duration.fill("1");
  await minus.click();
  ensure(await duration.inputValue() === "1", "Minus passed the minimum duration");
  await duration.fill("365");
  await plus.click();
  ensure(await duration.inputValue() === "365", "Plus passed the maximum duration");
  for (const invalid of ["", "0", "366", "1.5"]) {
    await duration.fill(invalid);
    await plus.click();
    ensure(await duration.inputValue() === invalid && !await duration.evaluate(element => element.checkValidity()), "Stepper silently repaired an invalid draft");
  }
  await duration.fill("4");
  ensure(await page.locator("#editor-form").evaluate(element => new FormData(element).getAll("durationDays").length) === 1, "Duration has multiple submitted owners");
  ensure((await state()).revision === before.revision, "Duration buttons saved without Save");
  await page.locator("#cancel-editor").click();
  await page.locator(".activity-name").first().click();
  ensure(await duration.inputValue() === "3" && (await state()).revision === before.revision, "Cancel retained duration edits");
  await plus.click();
  const savedResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/activities"));
  await page.locator("#editor-form").getByRole("button", {name: "Save", exact: true}).click();
  ensure((await savedResponse).ok(), "Duration save failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  await page.reload();
  await page.waitForFunction(() => typeof planner !== "undefined" && planner?.id);
  await page.evaluate(() => { today = () => "2026-10-14"; alertAcknowledged = true; render(); });
  await page.locator(".activity-name").first().click();
  const saved = await state();
  ensure(await duration.inputValue() === "4" && saved.plans[0].activities[0].progress === 50 && saved.plans[0].activities[0].start === "2026-10-13", "Saving duration lost progress/start or did not survive reload");
  await page.screenshot({path: "/tmp/pocketplanner-duration-desktop.png"});
  await page.setViewportSize({width: 390, height: 844});
  const mobile = await page.locator("#editor").evaluate(element => ({width: element.clientWidth, contentWidth: element.scrollWidth, pageOverflow: document.documentElement.scrollWidth > innerWidth}));
  ensure(mobile.contentWidth <= mobile.width && !mobile.pageOverflow, "Duration controls overflow on mobile");
  const order = await page.locator(".duration-stepper").evaluate(element => [...element.children].map(child => child.getBoundingClientRect().x));
  ensure(order[0] < order[1] && order[1] < order[2], "Minus, field and plus are not in the requested order");
  await page.screenshot({path: "/tmp/pocketplanner-duration-mobile.png"});
  ensure(!errors.length, `Browser errors: ${errors.join("; ")}`);
  return {checks: "minus/field/plus, live full-estimate preview, keyboard, limits, invalid drafts, Cancel, Save/reload, viewer permissions, forecast blocker delay versus recorded time, mobile", revision: saved.revision, mobile};
}
