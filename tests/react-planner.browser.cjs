const pause = duration => new Promise(resolve => setTimeout(resolve, duration));

async function startServer() {
  if (container) return container.start();
  const log = fs.createWriteStream(path.join(temporary, 'application.log'), {flags: 'a'});
  const child = spawn('java', ['-jar', jar, '--server.port=0', '--server.address=127.0.0.1', '--TESTPLANNER_DB=' + path.join(temporary, 'planner.sqlite3'), '--POCKETHIVE_AUTH_BASE_URL=' + auth,
    '--POCKETHIVE_BASE_URL=http://127.0.0.1:' + fakePh.address().port, '--POCKETHIVE_PUBLIC_URL=' + new URL(auth).origin, '--POCKETPLANNER_INSTANCE_ID=' + instance], {cwd: temporary, stdio: ['ignore', 'pipe', 'pipe']});
  let output = '';
  child.stdout.on('data', bytes => { output = (output + bytes.toString()).slice(-16384); log.write(bytes); });
  child.stderr.on('data', bytes => log.write(bytes));
  const stop = async () => {
    if (child.exitCode === null && child.signalCode === null) {
      const exit = once(child, 'exit'); child.kill('SIGTERM');
      const timer = setTimeout(() => child.kill('SIGKILL'), 10000);
      try { await exit; } finally { clearTimeout(timer); }
    }
    log.end();
  };
  for (let attempt = 0; attempt < 600; attempt++) {
    const match = output.match(/Tomcat started on port ([0-9]+)/);
    if (match) return {origin: 'http://localhost:' + match[1], stop};
    if (child.exitCode !== null) throw new Error('Candidate failed startup');
    await pause(50);
  }
  await stop(); throw new Error('Candidate startup timeout');
}

