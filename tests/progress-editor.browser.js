async (page) => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const state = () => page.evaluate(async () => (await fetch("/api/state")).json());
  const initial = await state();
  ensure(initial.plans.length === 0, "Run only against an isolated server with an empty test database");
  await page.setViewportSize({width: 1171, height: 1252});
  await page.evaluate(() => window.PockerAuth.logout());
  await page.reload();
  await page.locator("#auth-button").click();
  await page.locator("#auth-username").fill("local-admin");
  await page.locator("#auth-form").getByRole("button", {name: "Sign in", exact: true}).click();
  await page.locator("#auth-dialog").waitFor({state: "hidden"});
  await page.evaluate(async () => {
    const fixture = await (await fetch("/example-plan.json")).json();
    fixture.plans[0].activities[0].start = "2026-10-13";
    fixture.plans[0].activities[0].progress = 25;
    fixture.plans[0].activities[0].dateConfirmed = true;
    const response = await fetch("/api/state", {method: "PUT", headers: {"Content-Type": "application/json", ...window.PockerAuth.headers()}, body: JSON.stringify(fixture)});
    if (!response.ok) throw new Error(await response.text());
  });
  await page.reload();
  await page.locator(".activity-name").first().click();
  const number = page.getByRole("spinbutton", {name: "Progress · %", exact: true});
  const slider = page.getByRole("slider", {name: "Progress slider", exact: true});
  const done = page.getByRole("button", {name: "Done", exact: true});
  const save = page.locator("#editor-form").getByRole("button", {name: "Save", exact: true});
  ensure(await number.inputValue() === "25" && await slider.inputValue() === "25", "Saved progress was not loaded into both controls");
  await slider.focus();
  await page.keyboard.press("End");
  ensure(await number.inputValue() === "100", "Slider did not synchronize its upper bound");
  await page.keyboard.press("Home");
  ensure(await number.inputValue() === "0", "Slider did not synchronize its lower bound");
  await page.keyboard.press("ArrowRight");
  ensure(await number.inputValue() === "1", "Slider keyboard step failed");
  await number.fill("57");
  ensure(await slider.inputValue() === "57", "Typed progress did not synchronize the slider");
  await number.press("ArrowUp");
  ensure(await number.inputValue() === "58" && await slider.inputValue() === "58", "Numeric increment failed");
  await number.press("ArrowDown");
  ensure(await number.inputValue() === "57" && await slider.inputValue() === "57", "Numeric decrement failed");
  const progressFields = await page.locator("#editor-form").evaluate(element => new FormData(element).getAll("progress"));
  ensure(progressFields.length === 1 && progressFields[0] === "57", "Progress has more than one submitted owner");
  const beforeDraft = await state();
  for (const invalid of ["101", "-1", "12.5", ""]) {
    await number.fill(invalid);
    ensure(!await number.evaluate(element => element.checkValidity()), "Invalid progress draft was accepted");
    await save.click();
    ensure(await page.locator("#editor").evaluate(element => element.open), "Invalid draft closed the editor");
    ensure((await state()).revision === beforeDraft.revision, "Invalid draft was saved");
  }
  await done.click();
  ensure(await number.inputValue() === "100" && await slider.inputValue() === "100", "Done did not set both controls to 100");
  ensure((await state()).revision === beforeDraft.revision, "Done submitted the form without Save");
  await page.locator("#cancel-editor").click();
  await page.locator(".activity-name").first().click();
  ensure(await number.inputValue() === "25", "Cancel did not discard the draft");
  await done.click();
  const savedResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await save.click();
  ensure((await savedResponse).ok(), "Saving Done failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  const saved = await state();
  ensure(saved.plans[0].activities[0].progress === 100, "Saved progress is not complete");
  ensure(saved.plans[0].activities[0].durationDays === 2 && saved.plans[0].activities[0].start === "2026-10-13", "Progress editing changed the schedule");
  ensure(saved.plans[0].activities[0].status === beforeDraft.plans[0].activities[0].status, "Done overwrote the description");
  const track = await page.locator(".activity-row .track").first().evaluate(element => ({width: element.getBoundingClientRect().width, expected: Number.parseFloat(element.style.width)}));
  ensure(track.width > 0 && Math.abs(track.width - track.expected) < 1, "Gantt inline positioning styles are blocked or mis-sized");
  await page.getByRole("button", {name: "Collapse Example stream", exact: true}).click();
  ensure(await page.locator(".stream-summary-label").textContent() === "Example stream", "Collapsed bar has no stream name");
  ensure(await page.locator(".stream-progress").textContent() === "100%", "Stream progress did not refresh after Save");
  await page.reload();
  await page.locator(".activity-name").first().click();
  ensure(await number.inputValue() === "100" && await slider.inputValue() === "100", "Saved progress did not survive reload");
  await number.fill("37");
  await page.setViewportSize({width: 390, height: 844});
  const mobile = await page.locator("#editor").evaluate(element => ({width: element.clientWidth, contentWidth: element.scrollWidth, pageOverflow: document.documentElement.scrollWidth > innerWidth}));
  ensure(mobile.contentWidth <= mobile.width && !mobile.pageOverflow, "The editor overflows on mobile");
  await page.setViewportSize({width: 1171, height: 1252});
  const typedResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await save.click();
  ensure((await typedResponse).ok(), "Saving typed progress failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  await page.reload();
  await page.locator(".activity-name").first().click();
  ensure(await number.inputValue() === "37" && await slider.inputValue() === "37", "Typed progress did not survive reload");
  await page.locator("#close-editor").click();
  await page.locator("#auth-button").click();
  await page.locator(".activity-name").first().click();
  ensure(await number.isDisabled() && await slider.isDisabled() && await done.isDisabled(), "A view-only progress control is enabled");
  ensure(await page.locator("#editor-form button[type=submit]").isHidden(), "Viewers can see Save");
  await page.locator("#close-editor").click();
  return {checks: "slider, typing, native stepping, invalid inputs, Done, Cancel, Save, reload, read-only, rendered Gantt tracks, named collapsed bars, mobile layout", revision: (await state()).revision, mobile};
}
