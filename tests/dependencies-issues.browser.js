async (page) => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const state = () => page.evaluate(async () => (await fetch("/api/state")).json());
  ensure((await state()).plans.length === 0, "Run only against an isolated server with an empty test database");
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewportSize({width: 1171, height: 1252});
  await page.evaluate(() => window.PocketAuth.login("local-admin"));
  await page.evaluate(async () => {
    const fixture = await (await fetch("/example-plan.json")).json();
    const plan = fixture.plans[0];
    plan.streams.push({id: "next", name: "Next stream", description: "Synthetic next stream"});
    const root = {...plan.activities[0], id: "root", name: "Minimal", start: "2026-10-16", durationDays: 1, progress: 0, issueIds: [], dateConfirmed: true};
    plan.activities = [root,
      {...root, id: "heavy", name: "Heavy", start: "2026-10-30", durationDays: 3},
      {...root, id: "next-root", name: "Next root", streamId: "next", start: "2026-10-09"},
      {...root, id: "next-offset", name: "Offset root", streamId: "next", start: "2026-10-13"},
      {...root, id: "next-child", name: "Next child", streamId: "next", start: "2026-10-14", durationDays: 2, dependsOn: "next-root"}];
    plan.issues[0] = {...plan.issues[0], title: "Global blocker", scope: "ALL", streamIds: [], blocker: true};
    plan.issues.push({...plan.issues[0], id: "scoped", title: "First stream blocker", scope: "STREAMS", streamIds: ["demo"]});
    const response = await fetch("/api/state", {method: "PUT", headers: {"Content-Type": "application/json", ...window.PocketAuth.headers()}, body: JSON.stringify(fixture)});
    if (!response.ok) throw new Error(await response.text());
  });
  await page.reload();
  await page.getByRole("button", {name: "Acknowledged", exact: true}).click();
  const editor = page.locator("#editor");
  const start = page.getByLabel("Start date", {exact: true});
  const dependency = page.getByRole("combobox", {name: "Depends on · activity", exact: true});
  const openActivity = async id => { await page.locator(`.activity-name[data-id="${id}"]`).click(); };
  const saveEditor = async () => {
    const response = page.waitForResponse(result => result.request().method() === "PUT" && /\/api\/(?:state|activities)$/.test(result.url()));
    await page.locator("#editor-form .dialog-actions").getByRole("button", {name: "Save", exact: true}).click();
    ensure((await response).ok(), "Saving the editor failed");
    await editor.waitFor({state: "hidden"});
  };
  const bars = id => page.locator(`.bar[data-id="${id}"]`);
  const indentation = id => page.locator(`.activity-name[data-id="${id}"]`).evaluate(element => parseFloat(getComputedStyle(element).paddingInlineStart));
  const days = locator => locator.evaluateAll(elements => elements.map(element => [element.dataset.start, element.dataset.end]));
  const setWindow = async () => {
    await page.locator('.activity-name[data-id="root"]').waitFor({state: "visible"});
    if (await page.locator("#blocked-alert").evaluate(element => element.open)) await page.getByRole("button", {name: "Acknowledged", exact: true}).click();
    await page.evaluate(() => { timelineStart = "2026-10-11"; visibleDays = 28; renderGantt(); });
  };
  await setWindow();
  await openActivity("heavy");
  ensure(await page.getByRole("checkbox", {name: "Global blocker", exact: true}).isChecked(), "ALL blocker is not checked when legacy issueIds are empty");
  const options = await dependency.locator("option").evaluateAll(elements => elements.map(element => element.value));
  ensure(options.join(",") === ",root", "Activity dependencies include self or another stream");
  await dependency.selectOption("root");
  ensure(await start.inputValue() === "2026-10-19" && await start.getAttribute("readonly") !== null, "Dependency does not follow Minimal on Monday");
  ensure((await page.locator("#schedule-hint").textContent()).includes("21 Oct"), "Dependent duration preview is wrong");
  await page.getByRole("checkbox", {name: "Include weekends", exact: true}).check();
  ensure(await start.inputValue() === "2026-10-17", "Weekend-enabled dependency does not start on Saturday");
  await page.getByRole("checkbox", {name: "Include weekends", exact: true}).uncheck();
  await page.getByRole("checkbox", {name: "Start date confirmed by team", exact: true}).check();
  await saveEditor();
  ensure(await indentation("root") === 0 && await indentation("heavy") === 14, "Activity labels do not show one dependency level");
  let saved = await state();
  ensure(saved.plans[0].activities[1].dependsOn === "root" && saved.plans[0].activities[1].start === "2026-10-30", "Dependency rewrites the authored fallback date");
  ensure(saved.plans[0].activities[1].confirmedStart === "2026-10-19", "Confirmation does not track the scheduled date");
  await page.reload();
  await setWindow();
  ensure((await days(bars("heavy")))[0].join(",") === "2026-10-19,2026-10-21", "Dependent schedule does not survive reload");
  await openActivity("root");
  ensure(await dependency.locator('option[value="heavy"]').count() === 0, "A cyclic predecessor is selectable");
  await page.locator("#cancel-editor").click();
  await page.getByRole("button", {name: "Edit Next stream", exact: true}).click();
  await page.getByRole("combobox", {name: "Depends on · stream", exact: true}).selectOption("demo");
  await saveEditor();
  ensure((await days(bars("next-root")))[0][0] === "2026-10-22", "Next stream does not follow all predecessor activities");
  ensure(await indentation("next-root") === 0 && await indentation("next-child") === 14, "Stream dependency is confused with activity indentation");
  ensure((await days(bars("next-offset")))[0][0] === "2026-10-26", "Stream root spacing was lost");
  ensure(JSON.stringify(await days(bars("next-child"))) === '[["2026-10-23","2026-10-23"],["2026-10-26","2026-10-26"]]', "Stream shift loses internal dependencies or weekend gaps");
  await page.getByRole("button", {name: "Edit Example stream", exact: true}).click();
  ensure(await page.getByRole("combobox", {name: "Depends on · stream", exact: true}).locator('option[value="next"]').count() === 0, "Cyclic stream predecessor is selectable");
  await page.locator("#cancel-editor").click();
  const beforeDrag = (await state()).revision;
  const drag = async (locator, delta) => {
    const box = await locator.boundingBox();
    const dayWidth = await locator.evaluate(element => element.parentElement.clientWidth / Number(document.getElementById("range-days").value));
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + dayWidth * delta, box.y + box.height / 2, {steps: 8});
    await page.mouse.up();
  };
  const dragResponse = page.waitForResponse(result => result.request().method() === "PUT" && result.url().endsWith("/api/state"));
  await drag(bars("root"), 3);
  ensure((await dragResponse).ok(), "Root drag did not save");
  await page.waitForFunction(() => !ignoreClick);
  ensure((await state()).revision === beforeDrag + 1, "Drag issued multiple mutations");
  ensure((await days(bars("heavy")))[0][0] === "2026-10-20", "Dragging root did not move its activity successor");
  ensure((await days(bars("next-root")))[0][0] === "2026-10-23", "Dragging root did not cascade to the dependent stream");
  ensure(await bars("heavy").first().evaluate(element => element.classList.contains("tentative")), "Upstream movement retained obsolete date confirmation");
  await openActivity("heavy");
  ensure(!await page.getByRole("checkbox", {name: "Start date confirmed by team", exact: true}).isChecked(), "Editor retains obsolete confirmation");
  await page.locator("#cancel-editor").click();
  const lockedRevision = (await state()).revision;
  await drag(bars("heavy"), 1);
  if (await editor.evaluate(element => element.open)) await page.locator("#cancel-editor").click();
  ensure((await state()).revision === lockedRevision, "A dependent bar can be dragged independently");
  await openActivity("root");
  await page.getByRole("checkbox", {name: "Global blocker", exact: true}).uncheck();
  await page.getByRole("checkbox", {name: "First stream blocker", exact: true}).uncheck();
  await saveEditor();
  saved = await state();
  const globalIssue = saved.plans[0].issues[0];
  ensure(globalIssue.scope === "ACTIVITIES" && globalIssue.activityIds.length === 4 && !globalIssue.activityIds.includes("root"), "Unlink does not narrow ALL to the remaining activities");
  ensure(saved.plans[0].issues[1].activityIds.join(",") === "heavy", "Stream blocker does not retain its other activity");
  ensure(await page.locator('.activity-name[data-id="root"]').evaluate(element => !element.closest(".activity-row").classList.contains("blocked-stream")), "Unlinked activity still pulses red");
  ensure(await page.locator(".activity-row.blocked-stream").count() === 4, "Unlink clears other activities' blockers");
  await page.reload();
  await page.locator('.activity-name[data-id="root"]').waitFor({state: "visible"});
  ensure(!await page.locator("#blocked-alert").evaluate(element => element.open), "Partial blocking still triggers the fully blocked warning");
  await page.getByRole("tab", {name: /^Issues/}).click();
  const globalCard = page.locator("#issues .issue").filter({hasText: "Global blocker"});
  ensure(await globalCard.locator(".issue-scope").textContent() === "4 activities", "Issue still claims ALL after unlink");
  await globalCard.locator(".issue-title").click();
  ensure(await page.getByRole("combobox", {name: "Affects", exact: true}).inputValue() === "ACTIVITIES", "Issue editor does not reflect activity scope");
  ensure(!await page.locator('#scope-activities input[value="root"]').isChecked() && await page.locator('#scope-activities input[value="heavy"]').isChecked(), "Issue editor targets are wrong");
  await page.setViewportSize({width: 390, height: 844});
  const mobile = await editor.evaluate(element => ({width: element.clientWidth, contentWidth: element.scrollWidth, pageOverflow: document.documentElement.scrollWidth > innerWidth}));
  ensure(mobile.contentWidth <= mobile.width && !mobile.pageOverflow, "Activity-target controls overflow on mobile");
  await page.screenshot({path: ".playwright-mcp/dependencies-issues.png", fullPage: true});
  await page.setViewportSize({width: 1171, height: 1252});
  for (const input of await page.locator("#scope-activities input").all()) await input.uncheck();
  await saveEditor();
  ensure(await globalCard.locator(".issue-scope").textContent() === "No activities", "Empty scope still claims affected work");
  await globalCard.locator(".issue-title").click();
  await page.getByRole("combobox", {name: "Affects", exact: true}).selectOption("ALL");
  await saveEditor();
  await page.getByRole("button", {name: "Acknowledged", exact: true}).click();
  await page.getByRole("tab", {name: "Plan", exact: true}).click();
  await openActivity("root");
  ensure(await page.getByRole("checkbox", {name: "Global blocker", exact: true}).isChecked(), "Issue-side ALL retargeting is not reflected in Activity");
  await page.locator("#cancel-editor").click();
  await page.locator("#auth-button").click();
  await openActivity("heavy");
  ensure(await dependency.isDisabled(), "Viewer can edit dependencies");
  ensure(await page.getByRole("checkbox", {name: "Global blocker", exact: true}).isDisabled(), "Viewer can change issue assignments");
  await page.setViewportSize({width: 390, height: 844});
  ensure(await editor.evaluate(element => element.scrollWidth <= element.clientWidth && document.documentElement.scrollWidth <= innerWidth), "Activity dependency editor overflows on mobile");
  await page.locator("#close-editor").click();
  await page.setViewportSize({width: 1171, height: 1252});
  await page.evaluate(() => window.PocketAuth.login("local-admin"));
  await openActivity("heavy");
  await dependency.selectOption("");
  ensure(await start.inputValue() === "2026-10-30" && await start.getAttribute("readonly") === null, "Clearing the activity dependency does not restore manual scheduling");
  await saveEditor();
  ensure(await page.evaluate(() => schedules.activities.get("heavy").start) === "2026-10-30", "Cleared dependency still controls the saved start");
  await page.getByRole("button", {name: "Edit Next stream", exact: true}).click();
  await page.getByRole("combobox", {name: "Depends on · stream", exact: true}).selectOption("");
  await saveEditor();
  ensure(await page.evaluate(() => schedules.activities.get("next-root").start) === "2026-10-09", "Clearing the stream dependency does not restore authored roots");
  ensure(await page.evaluate(() => schedules.activities.get("next-child").start) === "2026-10-12", "Clearing the stream dependency removes an internal activity dependency");
  await openActivity("next-offset");
  await dependency.selectOption("next-child");
  await saveEditor();
  ensure(await indentation("next-offset") === 28, "Chained dependencies do not indent further");
  const beforeIndentRender = await state();
  await page.setViewportSize({width: 390, height: 844});
  const alignment = await page.locator(".activity-row").evaluateAll(rows => rows.map(row => ({right: row.querySelector(".activity-sub").getBoundingClientRect().right, overflow: row.querySelector(".row-label").scrollWidth > row.querySelector(".row-label").clientWidth})));
  ensure(alignment.every(row => !row.overflow && Math.abs(row.right - alignment[0].right) < 1), "Indentation moves percentages or overflows narrow labels");
  await page.screenshot({path: ".playwright-mcp/dependency-indent-mobile.png", fullPage: true});
  await page.setViewportSize({width: 1171, height: 1252});
  await page.screenshot({path: ".playwright-mcp/dependency-indent-desktop.png", fullPage: true});
  ensure(JSON.stringify(await state()) === JSON.stringify(beforeIndentRender), "Rendering indentation changed saved state");
  ensure(errors.length === 0, `Browser errors: ${errors.join(", ")}`);
  return {checks: "activity/stream dependencies, clearing dependencies, no cycles, exact successor dates, weekends, root spacing, cascade drag, confirmation, reload, issue unlink/retarget, partial blocking, empty targets, nested indentation, percentage alignment, mobile, viewer permissions", revision: (await state()).revision, mobile};
}
