async (page) => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  const state = () => page.evaluate(async () => (await fetch("/api/state")).json());
  const initial = await state();
  ensure(initial.plans.length === 0, "Run only against an isolated server with an empty test database");
  await page.setViewportSize({width: 1171, height: 1252});
  await page.evaluate(() => window.PockerAuth.logout());
  await page.reload();
  await page.locator("#auth-button").click();
  await page.locator("#auth-username").fill("local-admin");
  await page.locator("#auth-form").getByRole("button", {name: "Sign in", exact: true}).click();
  await page.locator("#auth-dialog").waitFor({state: "hidden"});
  await page.evaluate(async () => {
    const fixture = await (await fetch("/example-plan.json")).json();
    const plan = fixture.plans[0];
    plan.streams.push({id: "second", name: "Second stream", description: ""});
    plan.activities.push({...plan.activities[0], id: "second", name: "Second activity", streamId: "second"});
    plan.issues[0] = {...plan.issues[0], scope: "ALL", streamIds: [], blocker: true, descriptionIncomplete: true};
    plan.issues.push({...plan.issues[0], id: "scoped", title: "Stream-only issue", scope: "STREAMS", streamIds: ["demo"], descriptionIncomplete: false});
    plan.issues.push({...plan.issues[0], id: "note", title: "Closed note", blocker: false, open: false, descriptionIncomplete: false});
    const response = await fetch("/api/state", {method: "PUT", headers: {"Content-Type": "application/json", ...window.PockerAuth.headers()}, body: JSON.stringify(fixture)});
    if (!response.ok) throw new Error(await response.text());
  });
  await page.reload();
  await page.getByRole("button", {name: "Acknowledged", exact: true}).click();
  await page.getByRole("tab", {name: /^Issues/}).click();
  const status = page.getByRole("combobox", {name: "Issue status", exact: true});
  const issue = page.locator(".issue-title").filter({hasText: "Example issue"});
  ensure(await status.inputValue() === "active" && await page.locator("#issues .issue").count() === 2, "Active is not the default filter");
  ensure(await page.locator("#issues").getByText("incomplete", {exact: true}).count() === 1, "Missing incomplete list label");
  ensure(await page.locator("#issues button.blocker-toggle, #issues [data-toggle-blocker], #issues .scope-link").count() === 0, "Inline issue editing controls still exist");
  const beforeLabels = await state();
  const labels = await page.locator(".issue-kind, .issue-scope").evaluateAll(elements => elements.map(element => ({tag: element.tagName, tabIndex: element.tabIndex, text: element.textContent})));
  ensure(labels.every(label => label.tag === "SPAN" && label.tabIndex === -1 && !label.text.includes("▾")), "Issue labels suggest an interactive control");
  await page.locator(".issue-kind").first().click();
  await page.locator(".issue-scope").first().click();
  ensure(!await page.locator("#editor").evaluate(element => element.open), "A list label opened the editor");
  ensure(JSON.stringify(await state()) === JSON.stringify(beforeLabels), "A list label changed issue data");
  await issue.click();
  await page.getByRole("checkbox", {name: "Blocker", exact: true}).uncheck();
  const unmarkResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.locator("#editor-form .dialog-actions").getByRole("button", {name: "Save", exact: true}).click();
  ensure((await unmarkResponse).ok(), "Blocker editing inside the issue failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  ensure((await state()).plans[0].issues[0].blocker === false, "The editor did not clear the blocker flag");
  ensure(await page.locator("#issues .issue").filter({hasText: "Example issue"}).locator(".issue-kind").textContent() === "Issue", "Nonblocker label is misleading");
  await issue.click();
  await page.getByRole("checkbox", {name: "Blocker", exact: true}).check();
  const markResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.locator("#editor-form .dialog-actions").getByRole("button", {name: "Save", exact: true}).click();
  ensure((await markResponse).ok(), "Restoring the blocker flag inside the issue failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  await issue.click();
  ensure(await page.locator("input[name=open][type=checkbox]").count() === 0, "Open checkbox still exists");
  ensure(await page.getByRole("checkbox", {name: "Incomplete", exact: true}).isChecked(), "Incomplete flag was not loaded");
  ensure(await page.locator(".issue-description-heading input[name=descriptionIncomplete]").count() === 1, "Incomplete is not beside Description");
  ensure((await page.locator("#incomplete-hint").textContent()).includes("does not affect blockers"), "Incomplete has no functional explanation");
  const enterResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.getByRole("textbox", {name: "Issue title", exact: true}).press("Enter");
  ensure((await enterResponse).ok(), "Enter did not save the issue");
  await page.locator("#editor").waitFor({state: "hidden"});
  ensure((await state()).plans[0].issues[0].open === true, "Enter unexpectedly closed the issue");
  await issue.click();
  const before = await state();
  await page.getByRole("checkbox", {name: "Incomplete", exact: true}).uncheck();
  await page.locator("#cancel-editor").click();
  ensure(JSON.stringify(await state()) === JSON.stringify(before), "Cancel saved issue edits");
  await issue.click();
  await page.getByRole("textbox", {name: "Issue title", exact: true}).fill("");
  await page.getByRole("button", {name: "Close issue", exact: true}).click();
  ensure(await page.locator("#editor").evaluate(element => element.open), "Close issue bypassed form validation");
  ensure((await state()).revision === before.revision, "Invalid Close issue was saved");
  await page.getByRole("textbox", {name: "Issue title", exact: true}).fill("Example issue");
  const closeResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.getByRole("button", {name: "Close issue", exact: true}).click();
  ensure((await closeResponse).ok(), "Closing the issue failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  const closed = await state();
  ensure(closed.plans[0].issues[0].open === false && closed.plans[0].issues[0].blocker, "Close did not preserve blocker classification");
  ensure(closed.plans[0].issues[0].descriptionIncomplete, "Close lost the incomplete flag");
  const resolvedAt = closed.plans[0].issues[0].resolvedAt;
  ensure(typeof resolvedAt === "string" && Number.isFinite(Date.parse(resolvedAt)), "Close did not record a resolution timestamp");
  ensure(closed.plans[0].issues[1].open && JSON.stringify(closed.plans[0].activities) === JSON.stringify(before.plans[0].activities), "Close changed other blockers or activities");
  ensure(await page.locator("#issues .issue").count() === 1, "Closed issue remains in Active");
  await page.getByRole("tab", {name: "Plan", exact: true}).click();
  ensure(await page.locator(".gantt-row.group.blocked-stream").count() === 1, "Closing ALL cleared another stream's blocker");
  await page.getByRole("tab", {name: /^Issues/}).click();
  await status.selectOption("history");
  ensure(await page.locator("#issues .issue").count() === 2, "History does not show closed issues");
  ensure(await page.locator("#issues time").getAttribute("datetime") === resolvedAt, "History does not show the recorded resolution time");
  ensure((await page.locator("#issues .issue").filter({hasText: "Closed note"}).textContent()).includes("Not recorded"), "Historical closure has a guessed timestamp");
  await page.locator("#blocker-filter").click();
  ensure(await page.locator("#issues .issue").count() === 1, "Blocker filtering does not work in History");
  await issue.click();
  ensure(await page.getByRole("button", {name: "Reopen issue", exact: true}).isVisible(), "Closed issue has no Reopen action");
  await page.getByRole("textbox", {name: "Description", exact: true}).fill("Updated while closed");
  const saveResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.locator("#editor-form .dialog-actions").getByRole("button", {name: "Save", exact: true}).click();
  ensure((await saveResponse).ok(), "Saving a closed issue failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  ensure((await state()).plans[0].issues[0].open === false, "Save reopened a closed issue");
  ensure((await state()).plans[0].issues[0].resolvedAt === resolvedAt, "Editing a closed issue changed its resolution timestamp");
  await page.reload();
  ensure(await status.inputValue() === "active", "Reload does not default to Active");
  await status.selectOption("history");
  await issue.click();
  ensure(await page.getByRole("button", {name: "Reopen issue", exact: true}).isVisible(), "Closed state did not survive reload");
  ensure(await page.locator("#editor time").getAttribute("datetime") === resolvedAt, "Resolution timestamp did not survive reload");
  await page.getByRole("checkbox", {name: "Incomplete", exact: true}).uncheck();
  await page.getByRole("textbox", {name: "Description", exact: true}).fill("Complete description");
  await page.setViewportSize({width: 390, height: 844});
  const mobile = await page.locator("#editor").evaluate(element => ({width: element.clientWidth, contentWidth: element.scrollWidth, pageOverflow: document.documentElement.scrollWidth > innerWidth}));
  ensure(mobile.contentWidth <= mobile.width && !mobile.pageOverflow, "Issue editor overflows on mobile");
  const reopenResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.getByRole("button", {name: "Reopen issue", exact: true}).click();
  ensure((await reopenResponse).ok(), "Reopening failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  await page.getByRole("button", {name: "Show me the blockers", exact: true}).click();
  ensure(await status.inputValue() === "active", "Full-block warning did not reset History to Active");
  ensure(await page.locator("#issues .blocking-issue").count() === 2, "Reopened blocker is not active");
  ensure(await page.locator("#issues").getByText("incomplete", {exact: true}).count() === 0, "Cleared incomplete label is still visible");
  const reopened = (await state()).plans[0].issues[0];
  ensure(reopened.open === true && reopened.descriptionIncomplete === false && reopened.description === "Complete description", "Reopen did not save the current description edits");
  ensure(!reopened.resolvedAt, "Reopened issue retains a current resolution timestamp");
  const toolbar = await page.locator("#panel-issues .panel-toolbar").evaluate(element => ({width: element.clientWidth, contentWidth: element.scrollWidth}));
  ensure(toolbar.contentWidth <= toolbar.width, "Issue filters overflow on mobile");
  await page.setViewportSize({width: 1171, height: 1252});
  await page.locator("#add-issue").click();
  ensure(await page.locator("input[name=open]").inputValue() === "true", "New issues are not open by default");
  ensure(await page.locator("#editor-form .dialog-actions button[type=submit]").isVisible(), "Save visibility was changed by the lifecycle button");
  await page.getByRole("textbox", {name: "Issue title", exact: true}).fill("New issue");
  const createResponse = page.waitForResponse(response => response.request().method() === "PUT" && response.url().endsWith("/api/state"));
  await page.locator("#editor-form .dialog-actions").getByRole("button", {name: "Save", exact: true}).click();
  ensure((await createResponse).ok(), "Creating an issue failed");
  await page.locator("#editor").waitFor({state: "hidden"});
  ensure((await state()).plans[0].issues.at(-1).open === true, "New issue was saved closed");
  await page.locator("#auth-button").click();
  await issue.click();
  ensure(await page.getByRole("button", {name: "Close issue", exact: true}).isDisabled(), "Viewer can close an issue");
  ensure(await page.getByRole("checkbox", {name: "Incomplete", exact: true}).isDisabled(), "Viewer can change the incomplete flag");
  ensure(await page.locator("#editor-form .dialog-actions button[type=submit]").isHidden(), "Viewer can see Save");
  await page.locator("#close-editor").click();
  await status.selectOption("history");
  await page.locator("#blocker-filter").click();
  ensure(await page.locator("#issues .issue").count() === 1, "Viewer cannot browse History");
  return {checks: "noninteractive list labels, resolution timestamps, Close, Reopen, validation, Cancel, Save, persistence, blocker scope, incomplete labels, Active/History, warning filter reset, new issues, view-only, mobile", revision: (await state()).revision, mobile};
}
