import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { ApiError } from '../../api/plannerApi'
import type { CommandAck, RunCommand, RunOperation } from '../../api/types'
import { SwarmPanel, type SwarmPanelProps } from '../SwarmPanel'
import { accepted, apiFixture, deferred, operationFixture, planFixture, runFixture } from './fixtures'

beforeEach(() => {
  vi.useFakeTimers()
  vi.spyOn(document, 'hidden', 'get').mockReturnValue(false)
  vi.spyOn(window, 'confirm').mockReturnValue(true)
})
afterEach(() => { vi.useRealTimers() })
const settle = async () => { await act(async () => undefined) }
const tick = async (milliseconds: number) => { await act(async () => { await vi.advanceTimersByTimeAsync(milliseconds) }) }
function fixture(overrides: Partial<SwarmPanelProps> = {}) {
  const control = vi.fn().mockImplementation(async (command: RunCommand) => ({ ...accepted, idempotencyKey: command.idempotencyKey }))
  const operation = vi.fn().mockResolvedValue(operationFixture('DISPATCHED'))
  const { api, fetcher } = apiFixture({ control, operation })
  const props: SwarmPanelProps = { plan: planFixture(), run: runFixture(), outdated: false, api, open: true, onClose: vi.fn(), onRefresh: vi.fn(), onBusyChange: vi.fn(), ...overrides }
  return { ...render(<SwarmPanel {...props} />), props, control, operation, fetcher }
}

describe('authoritative exact-run commands (ported Node assertions)', () => {
  it('treats acceptance as pending and succeeds only on the exact operation; leaves PP untouched', async () => {
    const view = fixture()
    const before = JSON.stringify(view.props.plan)
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    expect(view.control).toHaveBeenCalledTimes(1)
    expect(screen.getByRole('status')).toHaveTextContent('Waiting for the authoritative outcome')
    expect(view.operation).toHaveBeenCalledWith('plan', 'shared', 'run-1', 'operation', expect.any(AbortSignal))
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(true)
    view.operation.mockResolvedValue(operationFixture('SUCCEEDED'))
    await tick(1500)
    expect(screen.getByRole('status')).toHaveTextContent('Start succeeded · confirmed by PH.')
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(false)
    expect(view.props.onRefresh).toHaveBeenCalledTimes(1)
    expect(JSON.stringify(view.props.plan)).toBe(before)
    expect(view.fetcher).not.toHaveBeenCalled()
  })
  it('retries an uncertain submission only explicitly, with the identical request and key', async () => {
    const view = fixture()
    view.control.mockRejectedValueOnce(new ApiError('Uncertain network result', 503))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    expect(view.control).toHaveBeenCalledTimes(1)
    expect(screen.getByRole('status')).toHaveTextContent('Outcome unknown')
    expect(screen.getByRole('button', { name: 'Start' })).toBeDisabled()
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(true)
    await tick(30000)
    expect(view.control).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('button', { name: 'Retry same request' }))
    await settle()
    expect(view.control).toHaveBeenCalledTimes(2)
    expect(view.control.mock.calls[1][0]).toEqual(view.control.mock.calls[0][0])
    expect(view.control.mock.calls[0][0]).toEqual({ planId: 'plan', swarmId: 'shared', runId: 'run-1', action: 'start', idempotencyKey: expect.any(String) })
  })
  it('does not offer command retry after definitive permission denial', async () => {
    const view = fixture()
    view.control.mockRejectedValueOnce(new ApiError('Denied by PH', 403))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    expect(screen.getByRole('status')).toHaveTextContent('Denied by PH')
    expect(screen.queryByRole('button', { name: 'Retry same request' })).toBeNull()
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(false)
    expect(view.operation).not.toHaveBeenCalled()
  })
  it.each(['REJECTED', 'FAILED', 'TIMED_OUT'])('reports terminal %s, never success or planning facts', async state => {
    const view = fixture()
    const before = JSON.stringify(view.props.plan)
    view.operation.mockResolvedValue(operationFixture(state))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    expect(screen.getByRole('status')).toHaveTextContent(`PH operation ${state}`)
    expect(screen.getByRole('status')).not.toHaveTextContent('succeeded')
    expect(JSON.stringify(view.props.plan)).toBe(before)
    expect(view.fetcher).not.toHaveBeenCalled()
  })
  it('requires explicit Stop confirmation and cancellation submits nothing', async () => {
    const view = fixture()
    vi.mocked(window.confirm).mockReturnValueOnce(false)
    fireEvent.click(screen.getByRole('button', { name: 'Stop' }))
    expect(view.control).not.toHaveBeenCalled()
    view.operation.mockResolvedValue({ ...operationFixture('SUCCEEDED'), type: 'STOP' })
    fireEvent.click(screen.getByRole('button', { name: 'Stop' }))
    await settle()
    expect(window.confirm).toHaveBeenCalledTimes(2)
    expect(view.control.mock.calls[0][0].action).toBe('stop')
    expect(screen.getByRole('status')).toHaveTextContent('Stop succeeded · confirmed by PH.')
  })
  it.each(['outdated', 'stale', 'historical', 'wrong-run', 'wrong-swarm', 'denied', 'busy'])('disables lifecycle controls for %s observations', state => {
    const run = runFixture()
    if (state === 'stale') run.runtime!.observationStale = true
    if (state === 'historical') run.runtime = null
    if (state === 'wrong-run') run.runtime!.runId = 'different'
    if (state === 'wrong-swarm') run.runtime!.id = 'different'
    if (state === 'denied') { run.canStart = false; run.canStop = false }
    if (state === 'busy') run.runtime!.activeOperation = { type: 'START', correlationId: 'other' }
    const view = fixture({ run, outdated: state === 'outdated' })
    for (const action of ['Start', 'Stop']) {
      const button = screen.getByRole('button', { name: action })
      expect(button).toBeDisabled()
      fireEvent.click(button)
    }
    expect(view.control).not.toHaveBeenCalled()
  })
  it.each([{ correlationId: 'wrong' }, { swarmId: 'wrong' }, { runtime: { runId: 'wrong' } }, { type: 'STOP' }, { state: 'UNKNOWN' }])('never accepts a mismatched or unknown operation: %j', async fields => {
    const view = fixture()
    view.operation.mockResolvedValue({ ...operationFixture('SUCCEEDED'), ...fields })
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    expect(screen.getByRole('status')).toHaveTextContent('Outcome not confirmed')
    expect(screen.getByRole('status')).not.toHaveTextContent('succeeded')
    expect(view.props.onRefresh).not.toHaveBeenCalled()
  })
  it.each([{ timeoutMs: 0 }, { timeoutMs: 180001 }, { timeoutMs: 2.5 }, { correlationId: '' }, { idempotencyKey: 'different' }])('retains uncertainty on an invalid acknowledgement: %j', async fields => {
    const view = fixture()
    view.control.mockImplementation(async (command: RunCommand) => ({ ...accepted, idempotencyKey: command.idempotencyKey, ...fields }))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    expect(screen.getByRole('status')).toHaveTextContent('Invalid PH command acknowledgement; outcome unknown')
    expect(screen.getByRole('button', { name: 'Retry same request' })).toBeEnabled()
    expect(view.operation).not.toHaveBeenCalled()
  })
  it('bounds a hung submission, aborts it, ignores late acceptance and retries the same key', async () => {
    const view = fixture()
    const delayed = deferred<CommandAck>()
    view.control.mockReturnValueOnce(delayed.promise)
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await tick(10000)
    const request = view.control.mock.calls[0][0]
    expect(view.control.mock.calls[0][1].aborted).toBe(true)
    expect(screen.getByRole('button', { name: 'Retry same request' })).toBeEnabled()
    await act(async () => { delayed.resolve({ ...accepted, idempotencyKey: request.idempotencyKey }) })
    expect(view.operation).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Retry same request' }))
    await settle()
    expect(view.control.mock.calls[1][0]).toEqual(request)
  })
  it('bounds the operation deadline independently, then checks only the original correlation', async () => {
    const view = fixture()
    const delayed = deferred<RunOperation>()
    view.control.mockImplementation(async (command: RunCommand) => ({ ...accepted, timeoutMs: 3000, idempotencyKey: command.idempotencyKey }))
    view.operation.mockReturnValueOnce(delayed.promise)
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    await tick(3000)
    expect(view.operation.mock.calls[0][4].aborted).toBe(true)
    expect(screen.getByRole('status')).toHaveTextContent('not been confirmed within the command timeout')
    expect(screen.queryByRole('button', { name: 'Retry same request' })).toBeNull()
    await act(async () => { delayed.resolve(operationFixture('SUCCEEDED')) })
    expect(screen.getByRole('status')).not.toHaveTextContent('succeeded')
    view.operation.mockResolvedValue(operationFixture('SUCCEEDED'))
    fireEvent.click(screen.getByRole('button', { name: 'Check outcome' }))
    await settle()
    expect(view.control).toHaveBeenCalledTimes(1)
    expect(view.operation.mock.calls.at(-1)!.slice(0, 4)).toEqual(['plan', 'shared', 'run-1', 'operation'])
    expect(screen.getByRole('status')).toHaveTextContent('Start succeeded · confirmed by PH.')
  })
  it('retains a pending command while hidden, polling it to terminal and reporting busy to its parent', async () => {
    const view = fixture()
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    view.rerender(<SwarmPanel {...view.props} open={false} />)
    expect(view.container.querySelector('aside')).not.toBeVisible()
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(true)
    view.operation.mockResolvedValue(operationFixture('SUCCEEDED'))
    await tick(1500)
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(false)
    expect(view.props.onRefresh).toHaveBeenCalledTimes(1)
    view.rerender(<SwarmPanel {...view.props} />)
    expect(screen.getByRole('status')).toHaveTextContent('Start succeeded · confirmed by PH.')
    expect(view.control).toHaveBeenCalledTimes(1)
  })
  it('retains an in-flight submission when closed, following its later acceptance to completion', async () => {
    const view = fixture()
    const delayed = deferred<CommandAck>()
    view.control.mockReturnValueOnce(delayed.promise)
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    const request = view.control.mock.calls[0][0]
    view.rerender(<SwarmPanel {...view.props} open={false} />)
    expect(view.control.mock.calls[0][1].aborted).toBe(false)
    view.operation.mockResolvedValue(operationFixture('SUCCEEDED'))
    await act(async () => { delayed.resolve({ ...accepted, idempotencyKey: request.idempotencyKey }) })
    expect(view.props.onRefresh).toHaveBeenCalledTimes(1)
    view.rerender(<SwarmPanel {...view.props} />)
    expect(screen.getByRole('status')).toHaveTextContent('Start succeeded · confirmed by PH.')
  })
  it('bounds each operation request at ten seconds without inventing a terminal result', async () => {
    const view = fixture()
    view.operation.mockReturnValueOnce(new Promise(() => undefined))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    await tick(10000)
    expect(view.operation.mock.calls[0][4].aborted).toBe(true)
    expect(screen.getByRole('status')).toHaveTextContent('Outcome not confirmed')
    expect(view.props.onBusyChange).toHaveBeenLastCalledWith(true)
    view.operation.mockResolvedValue(operationFixture('SUCCEEDED'))
    await tick(1500)
    expect(screen.getByRole('status')).toHaveTextContent('Start succeeded · confirmed by PH.')
    expect(view.control).toHaveBeenCalledTimes(1)
  })
  it('pauses operation polling in hidden documents without pausing the command deadline', async () => {
    const view = fixture()
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    vi.spyOn(document, 'hidden', 'get').mockReturnValue(true)
    act(() => { document.dispatchEvent(new Event('visibilitychange')) })
    await tick(90000)
    expect(view.operation).toHaveBeenCalledTimes(1)
    expect(view.control).toHaveBeenCalledTimes(1)
    vi.spyOn(document, 'hidden', 'get').mockReturnValue(false)
    act(() => { document.dispatchEvent(new Event('visibilitychange')) })
    expect(screen.getByRole('button', { name: 'Check outcome' })).toBeEnabled()
    expect(screen.getByRole('status')).toHaveTextContent('not been confirmed within the command timeout')
  })
  it('retains an uncertain command when selection changes and blocks a retry for another run or stale data', async () => {
    const view = fixture()
    view.control.mockRejectedValueOnce(new Error('Lost response'))
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    view.rerender(<SwarmPanel {...view.props} run={{ ...runFixture(), runId: 'different' }} />)
    expect(screen.getByRole('status')).toHaveTextContent('Command for shared / run-1:')
    expect(screen.getByRole('button', { name: 'Retry same request' })).toBeDisabled()
    view.rerender(<SwarmPanel {...view.props} outdated />)
    expect(screen.getByRole('button', { name: 'Retry same request' })).toBeDisabled()
    view.rerender(<SwarmPanel {...view.props} />)
    expect(screen.getByRole('button', { name: 'Retry same request' })).toBeEnabled()
  })
  it('aborts and clears pending state on explicit auth-context remount; late old outcomes cannot update the new panel', async () => {
    const view = fixture()
    const delayed = deferred<RunOperation>()
    view.operation.mockReturnValueOnce(delayed.promise)
    fireEvent.click(screen.getByRole('button', { name: 'Start' }))
    await settle()
    view.rerender(<SwarmPanel key="new-auth-context" {...view.props} />)
    expect(view.operation.mock.calls[0][4].aborted).toBe(true)
    await act(async () => { delayed.resolve(operationFixture('SUCCEEDED')) })
    expect(screen.getByRole('status')).toBeEmptyDOMElement()
    expect(screen.getByRole('button', { name: 'Start' })).toBeEnabled()
    expect(view.props.onRefresh).not.toHaveBeenCalled()
  })
})

describe('panel presentation', () => {
  it('renders only safe runtime fields and an exact backend HTTPS journal link', () => {
    const run = runFixture()
    Object.assign(run.runtime!, { secretConfiguration: 'must-not-render' })
    Object.assign(run.runtime!.workers[0], { token: 'must-not-render' })
    fixture({ run })
    const link = screen.getByRole('link', { name: /Open PH journal/ })
    expect(link).toHaveAttribute('href', run.journalUrl)
    expect(link).toHaveAttribute('target', '_blank')
    expect(link).toHaveAttribute('rel', 'noopener noreferrer')
    expect(screen.queryByText('must-not-render')).toBeNull()
    expect(screen.getByText(/associations, not a claim/)).toBeVisible()
    expect(screen.getByRole('table')).toBeVisible()
  })
  it('preserves the backend-provided HTTP local PH journal link', () => {
    const journalUrl = 'http://localhost:8089/journal/swarms/shared?runId=run-1'
    fixture({ run: { ...runFixture(), journalUrl } })
    expect(screen.getByRole('link', { name: /Open PH journal/ })).toHaveAttribute('href', journalUrl)
  })
  it.each(['javascript:alert(1)', 'https://user:pass@ph.example/journal?runId=run-1',
    'https://ph.example/journal?runId=run-1&access_token=secret', 'https://ph.example/journal?runId=other',
    'https://ph.example/journal?runId=run-1&runId=other'])('rejects unsafe or wrong-run journal URL %s', journalUrl => {
    fixture({ run: { ...runFixture(), journalUrl } })
    expect(screen.queryByRole('link')).toBeNull()
    expect(screen.getByText(/safe HTTP\(S\) journal link is unavailable/)).toBeVisible()
  })
  it('closes on Escape, without treating close as cancellation', () => {
    const view = fixture()
    expect(screen.getByRole('button', { name: 'Close swarm panel' })).toHaveFocus()
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(view.props.onClose).toHaveBeenCalledTimes(1)
  })
})
